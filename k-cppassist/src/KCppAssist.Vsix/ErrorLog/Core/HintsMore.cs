        /// <summary>
        /// エラーの中身(名前、クラス)を使った、この 1 件だけの説明。なければ null。
        /// 一般的なヒントは、同じ文がエラーの数だけ並ぶので、名前を入れて具体的にする。
        /// </summary>
        public static string Specific(Diag d)
        {
            if (d == null || d.Sev != Sev.Error) return null;
            var q = Quoted(d.Message);
            switch (d.Code)
            {
                case "C2065":
                case "C3861":
                    if (q.Count > 0)
                        return "「" + q[0] + "」は、この場所から見えていません。" + q[0] + " を宣言しているヘッダーを #include します(カーソルを名前に置いて Alt+F)。std の名前なら、std:: を付けます。綴りの間違いも確かめます。";
                    break;
                case "C2039":
                    if (q.Count >= 2)
                        return "「" + q[1] + "」に、「" + q[0] + "」という名前のメンバーがありません。綴り、基底クラス、const の違い、クラスの宣言(ヘッダー)を確かめます。";
                    break;
                case "C2248":
                    if (q.Count > 0)
                        return "「" + q[0] + "」は、private か protected で、この場所からは使えません。使う側を変えるか、クラスの公開範囲を変えます。";
                    break;
                case "C2259":
                    if (q.Count > 0)
                        return "「" + q[0] + "」に、実装されていない純粋仮想関数があります。下の補足に、足りない関数が出ます。";
                    break;
                case "C1083":
                    if (d.MissingName.Length > 0)
                        return "「" + d.MissingName + "」が見つかりません。ファイルの場所と、追加のインクルード ディレクトリを確かめます。Alt+F が書く #include は、プロジェクトが使っているフォルダーの基準に合わせたパスです。";
                    break;
            }
            return null;
        }

        /// <summary>表にないコードのときの、見出しとヒント。</summary>
        public static Hint Fallback(Sev sev)
        {
            if (sev == Sev.Error)
                return new Hint("このエラーの解説はまだありません",
                    "メッセージを読み、示された場所と、その 1 つ前の行を確かめます。意味は、見出しの [詳細] から、公式のページで調べられます。エラーが複数あるときは、一番上のものから直します。");
            return new Hint("警告",
                "ビルドは止まりません。意図どおりか確かめます。意味は、見出しの [詳細] で調べられます。意図があるなら、#pragma warning で止められます。");
        }

        internal static List<string> Quoted(string s)
        {
            var list = new List<string>();
            if (string.IsNullOrEmpty(s)) return list;
            foreach (Match m in Regex.Matches(s, "'([^']+)'")) list.Add(m.Groups[1].Value);
            return list;
        }
